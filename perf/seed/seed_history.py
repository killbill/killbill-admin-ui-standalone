#!/usr/bin/env python3
"""
Seed a dedicated Kill Bill with ~a year of realistic history, using Kill Bill's test clock.

Unlike seed.py (everything dated today), this rewinds Kill Bill's clock --months back and replays them week by week:
customers sign up over time, trials convert, invoices and payments are generated by Kill Bill itself on their
billing dates, and along the way some customers upgrade or downgrade, add add-ons, cancel, get extra charges,
credits and refunds; a few never pay automatically (AUTO_PAY_OFF) and carry a balance. A handful of "large"
accounts also get a steady stream of charges so their pages (timeline, invoices, payments) are heavy.

REQUIREMENTS (read before running):
  * Kill Bill must run with test mode on (org.killbill.server.test.mode=true, or KILLBILL_SERVER_TEST_MODE=true in
    the Docker image): the clock endpoints only exist in test mode.
  * Kill Bill's clock is GLOBAL to the Kill Bill instance: every tenant on it sees the rewind. Use a dedicated
    Kill Bill with a FRESH, empty database. Never point this at a shared or production Kill Bill.
  * Turn test mode off again afterwards if the environment should match production; the script leaves the clock at
    the real current time, so nothing jumps when you do.

Only needs Python 3.8+ (standard library). Re-uses seed.py's helpers (same directory).

Example (500 accounts, 12 months, ~20-40 minutes depending on the server):
  python3 perf/seed/seed_history.py --killbill-url http://kb:8080 --kaui-url http://kaui:9090 \\
      --username admin --password password --accounts 500 --months 12
"""
