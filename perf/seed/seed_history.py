def weighted(rng, items):
    total = sum(w for _, w in items)
    pick = rng.uniform(0, total)
    for item, w in items:
        pick -= w
        if pick <= 0:
            return item
    return items[-1][0]


class Account:
    def __init__(self, index, profile, rng):
        self.index = index
        self.profile = profile
        self.rng = random.Random(rng.random())
        self.id = None
        self.currency = weighted(self.rng, [(c, w) for c, (w, _) in REGIONS.items()])
        self.autopay_off = self.rng.random() < 0.08
        self.subscriptions = []  # dicts: id, plan, product, bundle_id, monthly, active
        self.lock = threading.Lock()

    def active_bases(self):
        return [s for s in self.subscriptions if s['active'] and s['product'] in MONTHLY_BY_PRODUCT]


def create_account(kb, prefix, acct, tag_defs):
    rng = acct.rng
    first, last = rng.choice(FIRST_NAMES), rng.choice(LAST_NAMES)
    country, locale, tz, cities = rng.choice(REGIONS[acct.currency][1])
    city, state, postal = rng.choice(cities)
    business = rng.random() < 0.35
    company = f'{rng.choice(COMPANY_WORDS)} {rng.choice(COMPANY_SUFFIX[country])}' if business else None
    external_key = f'{prefix}-{acct.profile}-{acct.index:05d}'
    body = {
        'externalKey': external_key,
        'name': f'{first} {last}',
        'firstNameLength': len(first),
        'email': f'{first}.{last}.{acct.index}@example.com'.lower(),
        'currency': acct.currency,
        'timeZone': tz,
        'locale': locale,
        'address1': f'{rng.randint(1, 250)} {rng.choice(STREETS)}',
        'city': city,
        'state': state,
        'postalCode': f'{postal}{rng.randint(10, 99)}',
        'country': country,
        'phone': f'+{rng.randint(1, 49)} {rng.randint(100, 999)} {rng.randint(1000000, 9999999)}',
    }
    if company:
        body['company'] = company
    _, _, headers = kb.request('POST', '/1.0/kb/accounts', body)
    acct.id = KillBill.id_from_location(headers)

    kb.request('POST', f'/1.0/kb/accounts/{acct.id}/paymentMethods',
               {'pluginName': '__EXTERNAL_PAYMENT__', 'externalKey': f'{external_key}-pm'}, params={'isDefault': 'true'})
    tags = []
    if acct.autopay_off:
        tags.append(AUTO_PAY_OFF)
    if rng.random() < 0.10:
        tags.append(tag_defs['vip'])
    if business and rng.random() < 0.15:
        tags.append(tag_defs['partner'])
    if tags:
        kb.request('POST', f'/1.0/kb/accounts/{acct.id}/tags', tags)
    fields = [{'name': 'segment', 'value': ('enterprise' if rng.random() < 0.2 else 'smb') if business else 'consumer'}]
    if business:
        fields.append({'name': 'crm_id', 'value': f'CRM-{rng.randint(100000, 999999)}'})
    kb.request('POST', f'/1.0/kb/accounts/{acct.id}/customFields', fields)

    add_base_subscription(kb, acct)
    if rng.random() < 0.10:  # a second product line
        add_base_subscription(kb, acct)


def add_base_subscription(kb, acct):
    rng = acct.rng
    plan, product, _price_list, monthly = weighted(rng, BASE_PLANS)
    _, _, headers = kb.request('POST', '/1.0/kb/subscriptions',
                               {'accountId': acct.id, 'planName': plan})  # the plan name implies its price list
    sub_id = KillBill.id_from_location(headers)
    _, sub, _ = kb.request('GET', f'/1.0/kb/subscriptions/{sub_id}')
    acct.subscriptions.append({'id': sub_id, 'plan': plan, 'product': product, 'bundle_id': sub['bundleId'],
                               'monthly': monthly, 'active': True})
    if product in ADDONS and rng.random() < 0.30:
        add_addon(kb, acct, acct.subscriptions[-1])


def add_addon(kb, acct, base):
    taken = {s['plan'] for s in acct.subscriptions if s['bundle_id'] == base['bundle_id'] and s['active']}
    choices = [p for p in ADDONS.get(base['product'], []) if p not in taken]
    if not choices:
        return
    plan = acct.rng.choice(choices)
    _, _, headers = kb.request('POST', '/1.0/kb/subscriptions',
                               {'accountId': acct.id, 'bundleId': base['bundle_id'], 'planName': plan})
    acct.subscriptions.append({'id': KillBill.id_from_location(headers), 'plan': plan, 'product': 'ADD_ON',
                               'bundle_id': base['bundle_id'], 'monthly': True, 'active': True})


def last_payment(kb, acct):
    _, payments, _ = kb.request('GET', f'/1.0/kb/accounts/{acct.id}/payments')
    ok = [p for p in payments or [] if float(p.get('purchasedAmount') or 0) > float(p.get('refundedAmount') or 0)]
    return ok[-1] if ok else None


def week_events(kb, acct, charges_per_step, stats):
    """What happens to one existing customer during one week."""
    rng = acct.rng
    p = {k: v / WEEKS_PER_MONTH for k, v in MONTHLY.items()}
    with acct.lock:
        bases = acct.active_bases()
        if bases and rng.random() < p['cancel']:
            sub = rng.choice(bases)
            kb.request('DELETE', f'/1.0/kb/subscriptions/{sub["id"]}',
                       params={'entitlementPolicy': 'END_OF_TERM', 'billingPolicy': 'END_OF_TERM'})
            for s in acct.subscriptions:
                if s['bundle_id'] == sub['bundle_id']:
                    s['active'] = False
            stats['cancel'] += 1
            return
        monthly = [s for s in bases if s['monthly']]
        if monthly and rng.random() < p['change']:
            sub = rng.choice(monthly)
            target = rng.choice([pl for pr, pl in MONTHLY_BY_PRODUCT.items() if pr != sub['product']])
            try:
                kb.request('PUT', f'/1.0/kb/subscriptions/{sub["id"]}', {'planName': target})
                sub['plan'] = target
                sub['product'] = next(pr for pr, pl in MONTHLY_BY_PRODUCT.items() if pl == target)
                stats['change'] += 1
            except RuntimeError:
                stats['change_refused'] += 1  # e.g. add-ons not available on the new product
        addable = [s for s in bases if s['product'] in ADDONS]
        if addable and rng.random() < p['addon']:
            add_addon(kb, acct, rng.choice(addable))
            stats['addon'] += 1
        n_charges = charges_per_step if acct.profile == 'large' else (1 if rng.random() < p['charge'] else 0)
        for _ in range(n_charges):
            kb.request('POST', f'/1.0/kb/invoices/charges/{acct.id}',
                       [{'accountId': acct.id, 'amount': round(rng.uniform(5, 250), 2), 'currency': acct.currency,
                         'description': rng.choice(CHARGE_REASONS)}], params={'autoCommit': 'true'})
            stats['charge'] += 1
        if n_charges and not acct.autopay_off:
            # External charges aren't paid automatically: pay them (one payment per invoice) like the recurring ones
            kb.request('POST', f'/1.0/kb/accounts/{acct.id}/invoicePayments', params={'externalPayment': 'false'})
        if rng.random() < p['credit']:
            kb.request('POST', '/1.0/kb/credits', [{'accountId': acct.id, 'amount': round(rng.uniform(5, 50), 2),
                                                    'currency': acct.currency, 'description': 'Goodwill credit'}],
                       params={'autoCommit': 'true'})
            stats['credit'] += 1
        if rng.random() < p['refund']:
            payment = last_payment(kb, acct)
            if payment:
                amount = round(min(float(payment['purchasedAmount']) - float(payment.get('refundedAmount') or 0),
                                   rng.uniform(5, 60)), 2)
                if amount > 0:
                    kb.request('POST', f'/1.0/kb/invoicePayments/{payment["paymentId"]}/refunds',
                               {'amount': amount, 'isAdjusted': False})
                    stats['refund'] += 1
        if acct.autopay_off and rng.random() < p['manual_pay']:
            _, account, _ = kb.request('GET', f'/1.0/kb/accounts/{acct.id}', params={'accountWithBalance': 'true'})
            if float(account.get('accountBalance') or 0) > 0:
                kb.request('POST', f'/1.0/kb/accounts/{acct.id}/invoicePayments', params={'externalPayment': 'false'})
                stats['manual_pay'] += 1


def summarize(kb, acct, kb_tenant_id, prefix):
    _, bundles, _ = kb.request('GET', f'/1.0/kb/accounts/{acct.id}/bundles')
    _, invoices, _ = kb.request('GET', f'/1.0/kb/accounts/{acct.id}/invoices')
    _, payments, _ = kb.request('GET', f'/1.0/kb/accounts/{acct.id}/payments')
    bundle = (bundles or [{}])[0]
    subscription = (bundle.get('subscriptions') or [{}])[0]
    return {
        'kb_tenant_id': kb_tenant_id,
        'account_id': acct.id,
        'external_key': f'{prefix}-{acct.profile}-{acct.index:05d}',
        'profile': acct.profile,
        'bundle_id': bundle.get('bundleId', ''),
        'subscription_id': subscription.get('subscriptionId', ''),
        'invoice_id': (invoices or [{}])[-1].get('invoiceId', ''),
        'payment_id': (payments or [{}])[-1].get('paymentId', ''),
        'nb_invoices': len(invoices or []),
        'nb_payments': len(payments or []),
    }


def run_parallel(pool, fn, items):
    errors = []
    for future in [pool.submit(fn, item) for item in items]:
        try:
            future.result()
        except RuntimeError as e:
            errors.append(str(e))
    return errors


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--killbill-url', default=os.environ.get('KILLBILL_URL', 'http://127.0.0.1:8080'))
    p.add_argument('--kaui-url', default=os.environ.get('KAUI_URL', 'http://127.0.0.1:9090'),
                   help='Kaui base URL, including the context path if not deployed at / (e.g. http://host:8080/kaui)')
    p.add_argument('--username', default=os.environ.get('KB_USERNAME', 'admin'))
    p.add_argument('--password', default=os.environ.get('KB_PASSWORD', 'password'))
    p.add_argument('--tenant-name', default='perf')
    p.add_argument('--api-key', default=os.environ.get('KB_API_KEY', 'perf'))
    p.add_argument('--api-secret', default=os.environ.get('KB_API_SECRET', 'perf-secret'))
    p.add_argument('--catalog', default=os.path.join(HERE, 'SpyCarAdvanced.xml'))
    p.add_argument('--prefix', default='perf')
    p.add_argument('--accounts', type=int, default=500, help='number of customers (regular + large)')
    p.add_argument('--large-accounts', type=int, default=5, help='how many of them get heavy activity')
    p.add_argument('--large-charges', type=int, default=300, help='extra charges per large account over the history')
    p.add_argument('--months', type=int, default=12, help='how far back the history starts')
    p.add_argument('--threads', type=int, default=8)
    p.add_argument('--clock-timeout', type=int, default=300, help='seconds Kill Bill may take to catch up per clock move')
    p.add_argument('--random-seed', type=int, default=42, help='same seed = same customers and events')
    p.add_argument('--skip-kaui', action='store_true', help='do not register the tenant in Kaui')
    p.add_argument('--yes', action='store_true', help='do not ask for confirmation before moving the clock')
    p.add_argument('--output', default=os.path.join(HERE, '..', 'gatling', 'src', 'test', 'resources', 'data', 'accounts.csv'))
    args = p.parse_args()

    kb = KillBill(args.killbill_url, args.username, args.password, args.api_key, args.api_secret)
    rng = random.Random(args.random_seed)

    # Tenant + catalog (retried: a Kill Bill that just started can reject the first catalog upload)
    try:
        kb.request('POST', '/1.0/kb/tenants', {'apiKey': kb.api_key, 'apiSecret': kb.api_secret, 'externalKey': args.tenant_name},
                   tenant=False, params={'useGlobalDefault': 'false'})
        print(f'Created tenant {kb.api_key}')
    except RuntimeError as e:
        if '409' not in str(e):
            raise
        print(f'Tenant {kb.api_key} already exists')
    _, tenant, _ = kb.request('GET', '/1.0/kb/tenants', params={'apiKey': kb.api_key}, tenant=False)
    kb_tenant_id = tenant['tenantId']

    # Test mode + empty tenant checks
    try:
        _, clock, _ = kb.request('GET', '/1.0/kb/test/clock')
    except RuntimeError as e:
        sys.exit(f'ERROR: Kill Bill test clock not available ({e}).\n'
                 'Start Kill Bill with org.killbill.server.test.mode=true (KILLBILL_SERVER_TEST_MODE=true).')
    _, existing, _ = kb.request('GET', '/1.0/kb/accounts/pagination', params={'offset': 0, 'limit': 1})
    if existing:
        sys.exit(f'ERROR: tenant {kb.api_key} already has accounts. This script needs an empty tenant on a Kill Bill '
                 'with a fresh database (it rewinds the clock).')

    today = dt.datetime.now(dt.timezone.utc)
    start = (today.replace(day=1, hour=8, minute=0, second=0, microsecond=0) - dt.timedelta(days=1)).replace(day=1)
    for _ in range(args.months - 1):
        start = (start - dt.timedelta(days=1)).replace(day=1)
    print(f'Kill Bill clock is {clock["currentUtcTime"]}. It will be set back to {start:%Y-%m-%d} and replayed to now.')
    print('The clock is global: every tenant on this Kill Bill is affected. Use a dedicated Kill Bill with a fresh DB.')
    if not args.yes and input('Continue? [y/N] ').strip().lower() != 'y':
        sys.exit('Aborted.')

    for attempt in range(5):
        _, catalogs, _ = kb.request('GET', '/1.0/kb/catalog')
        if catalogs:
            break
        try:
            with open(args.catalog) as f:
                kb.request('POST', '/1.0/kb/catalog/xml', f.read(), content_type='text/xml')
            print(f'Uploaded catalog {os.path.basename(args.catalog)}')
            break
        except RuntimeError as e:
            if attempt == 4:
                raise
            print(f'  catalog upload refused, retrying ({str(e)[:80]})')
            time.sleep(5)
    tag_defs = {name: ensure_tag_definition(kb, name) for name in ('vip', 'partner')}

    def set_clock(when):
        kb.request('POST', '/1.0/kb/test/clock',
                   params={'requestedDate': when.strftime('%Y-%m-%dT%H:%M:%S.000Z'), 'timeoutSec': args.clock_timeout})

    set_clock(start)

    # The clock moves one day at a time, so Kill Bill bills every invoice on its real date.
    # Sign-ups: 30% on the first days, the rest spread over the period (steady growth). Each customer's weekly
    # events (see week_events) fall on their own weekday.
    days = (today - start).days
    accounts = [Account(i, 'large' if i < args.large_accounts else 'regular', rng) for i in range(args.accounts)]
    signup_day = {}
    for acct in accounts:
        early = acct.profile == 'large' or rng.random() < 0.30
        signup_day[acct.index] = rng.randrange(0, 7) if early else rng.randrange(7, max(8, days - 1))
    charges_per_step = max(1, round(args.large_charges / max(1, days / 7)))

    stats = {k: 0 for k in ('cancel', 'change', 'change_refused', 'addon', 'charge', 'credit', 'refund', 'manual_pay')}
    started = time.time()
    week_errors = 0
    with ThreadPoolExecutor(max_workers=args.threads) as pool:
        for day in range(days):
            new = [a for a in accounts if signup_day[a.index] == day]
            errors = run_parallel(pool, lambda a: create_account(kb, args.prefix, a, tag_defs), new)
            due = [a for a in accounts if a.id and signup_day[a.index] < day and (day - signup_day[a.index]) % 7 == 0]
            errors += run_parallel(pool, lambda a: week_events(kb, a, charges_per_step, stats), due)
            for e in errors[:3]:
                print(f'    warning: {e[:200]}')
            week_errors += len(errors)
            set_clock(start + dt.timedelta(days=day + 1))  # returns once Kill Bill has billed everything due that day
            if day % 7 == 6 or day == days - 1:
                active = sum(1 for a in accounts if a.id)
                print(f'  week of {start + dt.timedelta(days=day - 6):%Y-%m-%d}: {active} customers, {week_errors} errors '
                      f'({time.time() - started:.0f}s)', flush=True)
                week_errors = 0
        set_clock(dt.datetime.now(dt.timezone.utc))

        rows = [r for r in pool.map(lambda a: summarize(kb, a, kb_tenant_id, args.prefix), [a for a in accounts if a.id])]

    rows.sort(key=lambda r: r['external_key'])
    os.makedirs(os.path.dirname(os.path.abspath(args.output)), exist_ok=True)
    with open(args.output, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    total_inv = sum(r['nb_invoices'] for r in rows)
    total_pay = sum(r['nb_payments'] for r in rows)
    print(f'Done in {time.time() - started:.0f}s: {len(rows)} accounts, {total_inv} invoices, {total_pay} payments; '
          f'events {stats}')
    print(f'Wrote the Gatling feeder to {os.path.abspath(args.output)}')

    if not args.skip_kaui:
        register_tenant_in_kaui(args.kaui_url, args.username, args.password, args.tenant_name, args.api_key, args.api_secret)


